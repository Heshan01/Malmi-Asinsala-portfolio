function projectTimestamp(project: Project) {
  const dated = project.date.match(/\b\d{1,2}\s+(?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:tember)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?)\s+20\d{2}\b/i)?.[0];
  if (dated) return Date.parse(dated);
  const year = project.date.match(/\b20\d{2}\b/)?.[0] ?? project.year.match(/\b20\d{2}\b/)?.[0];
  return year ? Date.UTC(Number(year), 0, 1) : 0;
}

